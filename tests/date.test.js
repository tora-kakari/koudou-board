// このファイルは、todayJST()（日本時間の今日）のテストです。
import test from "node:test";
import assert from "node:assert/strict";
import { todayJST } from "../src/lib/date.js";

const at = (iso) => todayJST(new Date(iso));

test("世界標準時 14:59 は日本ではまだ同じ日（日本は23:59）", () => {
  assert.equal(at("2026-10-04T14:59:59.999Z"), "2026-10-04");
});

test("世界標準時 15:00 で日本の翌日になる（日本は0:00）", () => {
  assert.equal(at("2026-10-04T15:00:00.000Z"), "2026-10-05");
});

test("世界標準時の 0:00 は日本では同じ日の朝9時", () => {
  assert.equal(at("2026-10-04T00:00:00.000Z"), "2026-10-04");
});

test("月末：1月31日 15:00（UTC）は日本の2月1日", () => {
  assert.equal(at("2026-01-31T14:59:59.999Z"), "2026-01-31");
  assert.equal(at("2026-01-31T15:00:00.000Z"), "2026-02-01");
});

test("年末：12月31日 15:00（UTC）は日本の翌年1月1日", () => {
  assert.equal(at("2025-12-31T14:59:59.999Z"), "2025-12-31");
  assert.equal(at("2025-12-31T15:00:00.000Z"), "2026-01-01");
});

test("うるう日：2028年は2月29日がある", () => {
  assert.equal(at("2028-02-28T15:00:00.000Z"), "2028-02-29");
  assert.equal(at("2028-02-29T15:00:00.000Z"), "2028-03-01");
});

test("うるう年でない年：2027年は2月28日の次が3月1日", () => {
  assert.equal(at("2027-02-28T15:00:00.000Z"), "2027-03-01");
});

test("引数なしでも YYYY-MM-DD の形で返る", () => {
  assert.match(todayJST(), /^\d{4}-\d{2}-\d{2}$/);
});
